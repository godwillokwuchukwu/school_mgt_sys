/**
 * Apply the 3-in-1 theme palette CSS variables to the document
 */
export function applyThemePalette(paletteId) {
  const p = THEME_PALETTES.find((t) => t.id === paletteId) || THEME_PALETTES[0]
  if (typeof document !== 'undefined') {
    const root = document.documentElement
    root.style.setProperty('--bfa-navy', p.colors.primary)
    root.style.setProperty('--bfa-navy-dark', p.colors.secondary)
    root.style.setProperty('--bfa-navy-2', p.colors.secondaryTone)
    root.style.setProperty('--bfa-gold', p.colors.accent)
    root.style.setProperty('--bfa-gold-light', p.colors.accentLight)
    root.style.setProperty('--bfa-gold-hover', p.colors.accentHover)
    root.style.setProperty('--bfa-bg', p.colors.bg)
    root.style.setProperty('--bfa-text', p.colors.text)
    root.style.setProperty('--bfa-border', p.colors.border)
  }
  return p
}

export function getActiveThemePalette() {
  const cached = typeof window !== 'undefined' ? localStorage.getItem('riverside_theme_palette') : null
  return THEME_PALETTES.find((t) => t.id === cached) || THEME_PALETTES[0]
}

